        /// <summary>创建不依赖表格文件修改的四列基础合法模型，便于隔离验证转换规则。</summary>
        /// <returns>包含一行中文数据及四种基础类型的原始工作表。</returns>
        private RawSheet CreateValidSheet()
        {
            var sheet = new RawSheet(workbookPath, "Enemy");
            string[][] rows =
            {
                new[] { "id", "name", "amount", "enabled" },
                new[] { "int", "string", "double", "bool" },
                new[] { "唯一标识", "中文名称", "数值", "是否启用" },
                new[] { "1001", "测试敌人", "3.5", "true" }
            };
            for (int row = 0; row < rows.Length; row++)
                for (int column = 0; column < rows[row].Length; column++)
                    SetCell(sheet, row + 1, column + 1, rows[row][column]);
            return sheet;
        }

        /// <summary>设置内存模型中的指定单元格，行列坐标均从一开始。</summary>
        /// <param name="sheet">测试工作表。</param>
        /// <param name="row">Excel 行号。</param>
        /// <param name="column">Excel 列号。</param>
        /// <param name="value">单元格原始文本。</param>
        private static void SetCell(RawSheet sheet, int row, int column, string value)
        {
            if (!sheet.Rows.ContainsKey(row))
                sheet.Rows.Add(row, new SortedDictionary<int, RawCell>());
            sheet.Rows[row][column] = new RawCell(value);
        }

        /// <summary>在测试副本的某个 ZIP XML 部件中执行修改，其他条目按字节复制。</summary>
        /// <param name="entryName">需要修改的 Open XML 部件路径。</param>
        /// <param name="change">针对该 XML 文档的修改动作。</param>
        /// <param name="additionalParts">可选的新增或替换 XML 部件，用于构造共享字符串等真实输入。</param>
        private void RewriteXml(string entryName, Action<XDocument> change, IDictionary<string, XDocument> additionalParts = null)
        {
            string replacement = Path.Combine(testRoot, "rewrite-" + Guid.NewGuid().ToString("N") + ".xlsx");
            using (var input = ZipFile.OpenRead(workbookPath))
            using (var output = ZipFile.Open(replacement, ZipArchiveMode.Create))
            {
                foreach (ZipArchiveEntry entry in input.Entries)
                {
                    if (additionalParts != null && additionalParts.ContainsKey(entry.FullName)) continue;
                    ZipArchiveEntry copied = output.CreateEntry(entry.FullName, CompressionLevel.Optimal);
                    using (Stream source = entry.Open())
                    using (Stream destination = copied.Open())
                    {
                        if (entry.FullName == entryName)
                        {
                            XDocument document = XDocument.Load(source);
                            change(document);
                            document.Save(destination);
                        }
                        else
                            source.CopyTo(destination);
                    }
                }
                if (additionalParts != null)
                    foreach (var part in additionalParts)
                        using (Stream destination = output.CreateEntry(part.Key, CompressionLevel.Optimal).Open())
                            part.Value.Save(destination);
            }
            File.Copy(replacement, workbookPath, true);
            File.Delete(replacement);
        }

        /// <summary>从工作表 XML 定位一个已经存在的单元格。</summary>
        /// <param name="document">工作表 XML。</param>
        /// <param name="address">A1 形式的坐标。</param>
        /// <returns>目标单元格元素。</returns>
        private static XElement FindXmlCell(XDocument document, string address)
        {
            return document.Descendants(SpreadsheetNamespace + "c").Single(cell => (string)cell.Attribute("r") == address);
        }

        /// <summary>更新测试副本中的数值或文本单元格，保留行列位置。</summary>
        /// <param name="document">工作表 XML。</param>
        /// <param name="address">A1 形式的坐标。</param>
        /// <param name="value">缓存数值或内联字符串。</param>
        /// <param name="storageType">Open XML 存储类型，例如 n 或 inlineStr。</param>
        private static void SetXmlCell(XDocument document, string address, string value, string storageType)
        {
            XElement cell = FindXmlCell(document, address);
            cell.SetAttributeValue("t", storageType);
            cell.ReplaceNodes(storageType == "inlineStr"
                ? new XElement(SpreadsheetNamespace + "is", new XElement(SpreadsheetNamespace + "t", value))
                : new XElement(SpreadsheetNamespace + "v", value));
        }
