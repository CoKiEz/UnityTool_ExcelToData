using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace ExcelDataTool.Editor.Core
{
    /// <summary>把已经通过校验的表转换为确定性 JSON、运行时 C# 类型，并安全写入工程。</summary>
    public static class TableExporter
    {
        private const string GeneratedMarker = "// <auto-generated> ExcelDataTool: DO NOT EDIT MANUALLY </auto-generated>";
        private const string RecordMarker = "ExcelDataTool.ExportRecord.v1";
        private static readonly Encoding Utf8 = new UTF8Encoding(false, true);
        private static readonly object ExportGate = new object();

        /// <summary>生成并写入一张表；预检全部目标，使用所有权记录保护已有文件，并在写入失败时回滚。</summary>
        /// <param name="table">经过表结构及数据校验的中间模型。</param>
        /// <param name="projectRoot">包含 Assets 目录的 Unity 工程根目录。</param>
        /// <param name="jsonDirectory">工程内 Assets 下的 JSON 目录，支持工程相对路径或绝对路径。</param>
        /// <param name="codeDirectory">工程内 Assets 下的运行时代码目录，不允许包含 Editor 目录。</param>
        /// <returns>本次写入的 JSON、行类型及表类型的三个工程相对路径。</returns>
        /// <exception cref="ArgumentNullException">表为空。</exception>
        /// <exception cref="ArgumentException">工程或输出路径为空、越界，或包含不安全路径段。</exception>
        /// <exception cref="IOException">存在同名表、非本工具文件、被手改的生成文件，或文件读写失败。</exception>
        /// <exception cref="UnauthorizedAccessException">目录或文件缺少访问权限。</exception>
        public static IReadOnlyList<string> Export(
            ValidatedTable table,
            string projectRoot,
            string jsonDirectory = "Assets/GameData/Generated/Json",
            string codeDirectory = "Assets/GameData/Generated/Code")
        {
            if (table == null) throw new ArgumentNullException(nameof(table));
            lock (ExportGate)
            {
                string root = NormalizeProjectRoot(projectRoot);
                string jsonRoot = ResolveOutputDirectory(root, jsonDirectory);
                string codeRoot = ResolveOutputDirectory(root, codeDirectory);
                string recordRoot = ResolveOutputDirectory(root, "Assets/ExcelDataTool/ExportRecords");
                string recordPath = Path.Combine(recordRoot, table.Name + ".export.json");
                var writes = new List<PendingWrite>
                {
                    new PendingWrite(Path.Combine(jsonRoot, table.Name + ".json"), GenerateJson(table)),
                    new PendingWrite(Path.Combine(codeRoot, table.Name + "Row.cs"), GenerateRowCode(table)),
                    new PendingWrite(Path.Combine(codeRoot, table.Name + "Table.cs"), GenerateTableCode(table))
                };

                // 固定位置的记录使同名检查不依赖当前输出目录，换目录不会绕过表名唯一性保护。
                string sourceIdentity = GetSourceIdentity(root, table.SourcePath);
                byte[] previousRecord = ReadExistingFile(root, recordPath);
                VerifyOwnership(root, table, sourceIdentity, writes, previousRecord);
                JObject record = CreateRecord(root, table.Name, sourceIdentity, writes);
                writes.Add(new PendingWrite(recordPath, Serialize(record)) { Previous = previousRecord });

                Commit(root, writes);
                return writes.Take(3).Select(write => RelativePath(root, write.Path)).ToArray();
            }
        }

        /// <summary>按照固定的 rows 根对象协议生成 UTF-8 可保存的 JSON 文本。</summary>
        /// <param name="table">经过校验的表；行和字段顺序保持 Excel 中的顺序。</param>
        /// <returns>使用两个空格缩进、LF 换行且以换行结束的 JSON 文本。</returns>
        /// <exception cref="ArgumentNullException">表为空。</exception>
        public static string GenerateJson(ValidatedTable table)
        {
            if (table == null) throw new ArgumentNullException(nameof(table));
            var rows = new JArray();
            foreach (object[] values in table.Rows)
            {
                var row = new JObject();
                for (int index = 0; index < table.Columns.Count; index++)
                    row.Add(table.Columns[index].Name, new JValue(values[index]));
                rows.Add(row);
            }
            return Serialize(new JObject { ["rows"] = rows });
        }

        /// <summary>生成仅包含字段定义的可序列化行类型，不引用 UnityEditor 或具体配置数据。</summary>
        /// <param name="table">字段名和类型均已通过校验的表。</param>
        /// <returns>位于 ExcelDataTool.Generated 命名空间中的行类型 C# 文本。</returns>
        /// <exception cref="ArgumentNullException">表为空。</exception>
        public static string GenerateRowCode(ValidatedTable table)
        {
            if (table == null) throw new ArgumentNullException(nameof(table));
            var code = new StringBuilder();
            code.Append(GeneratedMarker).Append("\nusing System;\n\nnamespace ExcelDataTool.Generated\n{\n");
            code.Append("    /// <summary>").Append(EscapeDocumentation(table.Name)).Append(" 配置表的一行静态数据。</summary>\n");
            code.Append("    [Serializable]\n    public class ").Append(table.Name).Append("Row\n    {\n");
            foreach (TableColumn column in table.Columns)
            {
                string description = string.IsNullOrWhiteSpace(column.Description)
                    ? column.Name + " 配置字段。"
                    : column.Description;
                code.Append("        /// <summary>").Append(EscapeDocumentation(description)).Append("</summary>\n");
                code.Append("        public ").Append(column.TypeName).Append(' ').Append(column.Name);
                if (column.TypeName == "string") code.Append(" = string.Empty");
                code.Append(";\n");
            }
            code.Append("    }\n}\n");
            return code.ToString();
        }

        /// <summary>生成与 JSON 的 rows 数组对应的可序列化表容器。</summary>
        /// <param name="table">表名已通过校验的表。</param>
        /// <returns>位于 ExcelDataTool.Generated 命名空间中的表类型 C# 文本。</returns>
        /// <exception cref="ArgumentNullException">表为空。</exception>
        public static string GenerateTableCode(ValidatedTable table)
        {
            if (table == null) throw new ArgumentNullException(nameof(table));
            return GeneratedMarker + "\nusing System;\nusing System.Collections.Generic;\n\n" +
                "namespace ExcelDataTool.Generated\n{\n" +
                "    /// <summary>" + EscapeDocumentation(table.Name) + " 配置表，字段名与 JSON 根对象严格对应。</summary>\n" +
                "    [Serializable]\n    public class " + table.Name + "Table\n    {\n" +
                "        /// <summary>按 Excel 行顺序排列的静态配置记录。</summary>\n" +
                "        public List<" + table.Name + "Row> rows = new List<" + table.Name + "Row>();\n" +
                "    }\n}\n";
        }

        /// <summary>统一 JSON 换行、缩进与区域设置，避免操作系统或当前区域影响输出。</summary>
        private static string Serialize(JToken token)
        {
            var output = new StringBuilder();
            using (var text = new StringWriter(output, CultureInfo.InvariantCulture) { NewLine = "\n" })
            using (var writer = new JsonTextWriter(text) { Formatting = Formatting.Indented, Indentation = 2 })
                token.WriteTo(writer);
            return output + "\n";
        }

        /// <summary>把任意说明文本限制为一行 XML 文档内容，防止换行关闭注释后注入源代码。</summary>
        private static string EscapeDocumentation(string value)
        {
            var safe = new StringBuilder();
            foreach (char character in value ?? string.Empty)
            {
                if (char.IsControl(character) || character == '\u0085' || character == '\u2028' || character == '\u2029')
                    safe.Append(' ');
                else
                    safe.Append(character);
            }
            return safe.ToString().Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")
                .Replace("\"", "&quot;").Replace("'", "&apos;");
        }

        /// <summary>验证工程根目录存在，避免意外创建并写入一个并非 Unity 工程的位置。</summary>
        private static string NormalizeProjectRoot(string projectRoot)
        {
            if (string.IsNullOrWhiteSpace(projectRoot)) throw new ArgumentException("工程根目录不能为空。", nameof(projectRoot));
            string root = Path.GetFullPath(projectRoot).TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            if (!Directory.Exists(Path.Combine(root, "Assets")))
                throw new ArgumentException("工程根目录必须包含已存在的 Assets 目录。", nameof(projectRoot));
            return root;
        }

        /// <summary>限制输出位于工程 Assets 内，同时拒绝路径穿越、重解析点及 Editor 目录。</summary>
        private static string ResolveOutputDirectory(string root, string directory)
        {
            if (string.IsNullOrWhiteSpace(directory)) throw new ArgumentException("输出目录不能为空。", nameof(directory));
            string normalized = directory.Replace('\\', Path.DirectorySeparatorChar).Replace('/', Path.DirectorySeparatorChar);
            if (normalized.Split(Path.DirectorySeparatorChar).Any(part => part == "." || part == ".."))
                throw new ArgumentException("输出目录不允许包含 . 或 .. 路径段。", nameof(directory));
            string full = Path.GetFullPath(Path.IsPathRooted(normalized) ? normalized : Path.Combine(root, normalized))
                .TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            string assets = Path.Combine(root, "Assets");
            if (!IsWithin(assets, full)) throw new ArgumentException("输出目录必须位于当前工程的 Assets 内。", nameof(directory));
            foreach (string part in RelativePath(root, full).Split('/'))
            {
                if (string.Equals(part, "Editor", StringComparison.OrdinalIgnoreCase))
                    throw new ArgumentException("生成物必须供运行时使用，输出目录不能位于 Editor 内。", nameof(directory));
                if (part.EndsWith(".", StringComparison.Ordinal) || part.EndsWith(" ", StringComparison.Ordinal) ||
                    part.IndexOfAny(Path.GetInvalidFileNameChars()) >= 0 || part.IndexOfAny("<>:\"|?*".ToCharArray()) >= 0 ||
                    Regex.IsMatch(part, @"\A(CON|PRN|AUX|NUL|COM[1-9¹²³]|LPT[1-9¹²³])(?:\.|\z)", RegexOptions.IgnoreCase))
                    throw new ArgumentException("输出目录包含不安全或无效的路径段。", nameof(directory));
            }
            EnsureNoReparsePoints(root, full);
            if (File.Exists(full)) throw new IOException("输出目录位置已有文件：" + full);
            return full;
        }

        /// <summary>按操作系统路径规则确认子路径边界，避免将 AssetsOther 误判为 Assets 内。</summary>
        private static bool IsWithin(string parent, string path)
        {
            StringComparison comparison = Path.DirectorySeparatorChar == '\\' ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
            return string.Equals(parent, path, comparison) || path.StartsWith(parent + Path.DirectorySeparatorChar, comparison);
        }

        /// <summary>检查工程根到目标的每个已有路径段，拒绝符号链接或目录联接造成的越界。</summary>
        private static void EnsureNoReparsePoints(string root, string path)
        {
            if (!IsWithin(root, path)) throw new IOException("目标路径已越出工程目录：" + path);
            string current = path;
            while (true)
            {
                try
                {
                    if ((File.GetAttributes(current) & FileAttributes.ReparsePoint) != 0)
                        throw new IOException("为避免写入链接指向的其他位置，输出路径不允许包含符号链接或目录联接：" + current);
                }
                catch (FileNotFoundException) { }
                catch (DirectoryNotFoundException) { }
                if (string.Equals(current, root, StringComparison.OrdinalIgnoreCase)) break;
                current = Path.GetDirectoryName(current);
            }
        }

        /// <summary>将工程内文件转换为稳定的正斜杠相对路径。</summary>
        private static string RelativePath(string root, string path)
        {
            return path.Substring(root.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Replace('\\', '/');
        }

        /// <summary>工程内来源使用相对路径；工程外来源仅保存规范化路径的摘要，不泄露绝对路径。</summary>
        private static string GetSourceIdentity(string root, string sourcePath)
        {
            string source = Path.GetFullPath(Path.IsPathRooted(sourcePath) ? sourcePath : Path.Combine(root, sourcePath));
            string identity = IsWithin(root, source) ? RelativePath(root, source) : "external:" + source.Replace('\\', '/');
            if (Path.DirectorySeparatorChar == '\\') identity = identity.ToUpperInvariant();
            return IsWithin(root, source) ? identity : "external:" + Hash(Utf8.GetBytes(identity));
        }

        /// <summary>读取可覆盖目标的当前快照；目录和链接均不能冒充普通输出文件。</summary>
        private static byte[] ReadExistingFile(string root, string path)
        {
            EnsureNoReparsePoints(root, path);
            if (Directory.Exists(path)) throw new IOException("目标文件位置已被目录占用：" + path);
            return File.Exists(path) ? File.ReadAllBytes(path) : null;
        }

        /// <summary>检查记录的源身份、输出路径、文件摘要与代码标记，阻止覆盖其他内容。</summary>
        private static void VerifyOwnership(string root, ValidatedTable table, string sourceIdentity, List<PendingWrite> writes, byte[] previousRecord)
        {
            JObject record = null;
            if (previousRecord != null)
            {
                try { record = JObject.Parse(Utf8.GetString(previousRecord)); }
                catch (Exception exception) when (exception is JsonException || exception is DecoderFallbackException)
                {
                    throw new IOException("导出所有权记录损坏；为保护已有文件，已停止导出 " + table.Name + "。", exception);
                }
                if (!HasString(record, "tool") || !HasString(record, "table") || !HasString(record, "source") ||
                    !(record["files"] is JArray recordFiles) || recordFiles.Count != writes.Count ||
                    recordFiles.Any(item => !(item is JObject entry) || !HasString(entry, "path") || !HasString(entry, "sha256")) ||
                    recordFiles.Select(item => (string)item["path"]).Distinct(StringComparer.Ordinal).Count() != writes.Count)
                    throw new IOException("导出所有权记录的结构损坏；为保护已有文件，已停止导出 " + table.Name + "。");
                if ((string)record["tool"] != RecordMarker || (string)record["table"] != table.Name)
                    throw new IOException("导出记录不是本工具生成的有效记录，不能覆盖表 " + table.Name + "。");
                if ((string)record["source"] != sourceIdentity)
                    throw new IOException(Path.GetFileName(table.SourcePath) + " / " + table.Name + " / A1：表名已被其他 Excel 文件使用，已阻止同名覆盖。");
            }

            foreach (PendingWrite write in writes)
            {
                write.Previous = ReadExistingFile(root, write.Path);
                string relative = RelativePath(root, write.Path);
                JObject entry = (record?["files"] as JArray)?.OfType<JObject>().FirstOrDefault(item => (string)item["path"] == relative);
                if (record != null && entry == null)
                    throw new IOException("表 " + table.Name + " 已在其他输出路径导出，不能静默更换位置；请先检查 Assets/ExcelDataTool/ExportRecords 中的对应记录。");
                if (write.Previous == null) continue;
                if (entry == null)
                    throw new IOException("目标文件没有本工具的所有权记录，已阻止覆盖：" + relative);
                if ((string)entry["sha256"] != HashText(write.Previous))
                    throw new IOException("已有生成文件被手动修改或不属于记录中的版本，已阻止覆盖：" + relative);
                if (write.Path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) && !Utf8.GetString(write.Previous).StartsWith(GeneratedMarker, StringComparison.Ordinal))
                    throw new IOException("现有 C# 文件缺少自动生成标记，已阻止覆盖：" + relative);
            }
        }

        /// <summary>检查记录中的必填字符串，避免损坏的 JSON 结构触发难懂的强制转换异常。</summary>
        private static bool HasString(JObject value, string key)
        {
            return value[key]?.Type == JTokenType.String && !string.IsNullOrEmpty((string)value[key]);
        }

        /// <summary>构建不含时间戳的所有权记录，JSON 数据文件本身保持纯 rows 协议。</summary>
        private static JObject CreateRecord(string root, string tableName, string sourceIdentity, List<PendingWrite> writes)
        {
            var files = new JArray();
            foreach (PendingWrite write in writes)
                files.Add(new JObject { ["path"] = RelativePath(root, write.Path), ["sha256"] = HashText(write.Bytes) });
            return new JObject { ["tool"] = RecordMarker, ["table"] = tableName, ["source"] = sourceIdentity, ["files"] = files };
        }

        /// <summary>按 UTF-8 文本计算所有权摘要，仅统一 CRLF 为 LF，兼容 Git 的自动换行转换。</summary>
        private static string HashText(byte[] bytes)
        {
            try
            {
                // 内容与缩进仍严格校验；预检到提交的并发检查继续比较原始字节，不忽略中途编辑。
                return Hash(Utf8.GetBytes(Utf8.GetString(bytes).Replace("\r\n", "\n")));
            }
            catch (DecoderFallbackException exception)
            {
                throw new IOException("已有生成文件不是有效 UTF-8 文本，已阻止覆盖。", exception);
            }
        }

        /// <summary>计算 SHA-256 字节摘要，用于文件归属记录及工程外来源身份。</summary>
        private static string Hash(byte[] bytes)
        {
            using (SHA256 algorithm = SHA256.Create())
                return BitConverter.ToString(algorithm.ComputeHash(bytes)).Replace("-", string.Empty).ToLowerInvariant();
        }

        /// <summary>先完整落盘临时文件，再逐个原子替换；可恢复的异常会还原已经提交的目标。</summary>
        private static void Commit(string root, List<PendingWrite> writes)
        {
            bool completed = false;
            try
            {
                foreach (PendingWrite write in writes)
                {
                    EnsureNoReparsePoints(root, write.Path);
                    Directory.CreateDirectory(Path.GetDirectoryName(write.Path));
                    write.Temporary = Path.Combine(Path.GetDirectoryName(write.Path), "." + Path.GetFileName(write.Path) + "." + Guid.NewGuid().ToString("N") + ".tmp");
                    using (var stream = new FileStream(write.Temporary, FileMode.CreateNew, FileAccess.Write, FileShare.None))
                    {
                        stream.Write(write.Bytes, 0, write.Bytes.Length);
                        stream.Flush(true);
                    }
                }

                // 预检与提交之间若文件发生变化，则在写任何目标前停止；每次替换前再检查一次。
                foreach (PendingWrite write in writes) VerifySnapshot(root, write);
                foreach (PendingWrite write in writes)
                {
                    VerifySnapshot(root, write);
                    if (write.Previous == null)
                        File.Move(write.Temporary, write.Path);
                    else
                    {
                        write.Backup = write.Temporary + ".backup";
                        File.Replace(write.Temporary, write.Path, write.Backup);
                    }
                    write.Committed = true;
                }
                completed = true;
            }
            catch (Exception exportFailure)
            {
                var rollbackFailures = new List<string>();
                foreach (PendingWrite write in writes.AsEnumerable().Reverse().Where(item => item.Committed))
                {
                    try
                    {
                        // 回滚也不能覆盖外部的新修改；原件备份保留在原目录，供人工恢复。
                        byte[] current = ReadExistingFile(root, write.Path);
                        if (current == null || !current.SequenceEqual(write.Bytes))
                            throw new IOException("写入后目标再次变化，无法安全回滚。");
                        if (write.Previous == null) File.Delete(write.Path);
                        else File.Replace(write.Backup, write.Path, null);
                        write.Committed = false;
                    }
                    catch (Exception rollbackFailure)
                    {
                        rollbackFailures.Add(write.Path + "；备份：" + (write.Backup ?? "无（本次新建）") + "；" + rollbackFailure.Message);
                    }
                }
                if (rollbackFailures.Count > 0)
                    throw new IOException("导出失败，部分文件无法自动回滚，已保留可用备份：\n" + string.Join("\n", rollbackFailures), exportFailure);
                throw;
            }
            finally
            {
                foreach (PendingWrite write in writes)
                {
                    DeleteTemporaryIfPresent(write.Temporary);
                    if (completed || !write.Committed) DeleteTemporaryIfPresent(write.Backup);
                }
            }
        }

        /// <summary>确认目标与预检快照完全一致，防止等待期间的用户编辑被覆盖。</summary>
        private static void VerifySnapshot(string root, PendingWrite write)
        {
            byte[] current = ReadExistingFile(root, write.Path);
            if ((current == null) != (write.Previous == null) || (current != null && !current.SequenceEqual(write.Previous)))
                throw new IOException("目标文件在导出期间发生变化，已停止写入：" + write.Path);
        }

        /// <summary>仅清理本次创建的临时文件；清理失败不掩盖导出或回滚的真实结果。</summary>
        private static void DeleteTemporaryIfPresent(string path)
        {
            if (path == null) return;
            try { if (File.Exists(path)) File.Delete(path); }
            catch (IOException) { }
            catch (UnauthorizedAccessException) { }
        }

        /// <summary>保存一次文件写入的预检快照及事务状态，不把可变写入状态暴露给调用方。</summary>
        private sealed class PendingWrite
        {
            internal readonly string Path;
            internal readonly byte[] Bytes;
            internal byte[] Previous;
            internal string Temporary;
            internal string Backup;
            internal bool Committed;

            /// <summary>提前编码全部文本，使编码错误发生在任何目标写入之前。</summary>
            internal PendingWrite(string path, string content)
            {
                Path = path;
                Bytes = Utf8.GetBytes(content);
            }
        }
    }
}
